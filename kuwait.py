# بناء خرائط مساعدة: مدينة -> تقسيمة، ومدينة -> توصيل
CITY_TO_ZONE = {}
for _zone, _cities in ZONES.items():
    for _c in _cities:
        CITY_TO_ZONE[_c] = _zone


def delivery_for(city):
    return SPECIAL_DELIVERY.get(city, DEFAULT_DELIVERY)


def zone_for(city):
    return CITY_TO_ZONE.get(city, "")


def all_cities():
    """كل المدن مع تقسيمتها وسعر توصيلها — تُرسل للواجهة للبحث."""
    out = []
    for zone, cities in ZONES.items():
        for c in cities:
            out.append({"city": c, "zone": zone, "delivery": delivery_for(c)})
    return out


def lookup(city):
    """يرجّع التقسيمة والتوصيل لمدينة. لو مش معروفة يرجّع توصيل افتراضي وتقسيمة فارغة."""
    return {"city": city, "zone": zone_for(city), "delivery": delivery_for(city)}
